// Copies only the game-icons.net icons the app uses (tree nodes, crafted items, gear, bug hunt) into a
// small generated module, so the app never ships the full 4,000-icon set.
// Icons: game-icons.net, CC BY 3.0.   Usage: npm run icons
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { chromium } from "@playwright/test";

const set = JSON.parse(readFileSync(new URL("../node_modules/@iconify-json/game-icons/icons.json", import.meta.url)));

// Every source file is scanned, so a new icon reference anywhere is picked up automatically.
const srcDir = new URL("../src/", import.meta.url);
const files = readdirSync(srcDir, { recursive: true })
  .map(String)
  .filter((f) => /\.(ts|tsx)$/.test(f) && !f.endsWith(".generated.ts") && !/\.test\.tsx?$/.test(f));
const source = files.map((f) => readFileSync(new URL(f.replace(/\\/g, "/"), srcDir), "utf8")).join("\n");

// Matches d("icon-name", …) definitions and *Icon: "icon-name" fields.
const names = [...new Set([...source.matchAll(/(?:\bd\(\s*|[iI]con:\s*)"([a-z0-9-]+)"/g)].map((m) => m[1]))].sort();

const missing = names.filter((n) => !set.icons[n]);
if (missing.length) {
  console.error(`Unknown game-icons: ${missing.join(", ")}`);
  process.exit(1);
}

// Keep only path data: the renderer draws <path d> elements, so no raw SVG is ever injected.
const icons = names.map((n) => {
  const body = set.icons[n].body;
  const paths = [...body.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length || /<(?!path|\/path)/.test(body.replace(/<path[^>]*\/?>/g, ""))) {
    throw new Error(`Icon ${n} has non-path elements; pick another icon`);
  }
  return { name: n, paths };
});

// Many icons aren't centred on their 512 × 512 canvas, and some fill much less of it. Measure each
// drawing's real bounds in a browser (exact for curves and arcs) and fit a square viewBox around it,
// so every icon sits in the middle of its node at the same visual size.
const browser = await chromium.launch();
const page = await browser.newPage();
const boxes = await page.evaluate((list) => {
  const ns = "http://www.w3.org/2000/svg";
  const svg = document.createElementNS(ns, "svg");
  svg.setAttribute("viewBox", "0 0 512 512");
  document.body.append(svg);
  return list.map(({ paths }) => {
    const g = document.createElementNS(ns, "g");
    for (const d of paths) {
      const p = document.createElementNS(ns, "path");
      p.setAttribute("d", d);
      g.append(p);
    }
    svg.append(g);
    const b = g.getBBox();
    g.remove();
    return { cx: b.x + b.width / 2, cy: b.y + b.height / 2, size: Math.max(b.width, b.height) };
  });
}, icons);
await browser.close();

const round = (v) => Math.round(v * 10) / 10;
const entries = icons.map(({ name, paths }) => `  ${JSON.stringify(name)}: ${JSON.stringify(paths)},`).join("\n");
const viewBoxes = icons
  .map(({ name }, i) => {
    const { cx, cy, size } = boxes[i];
    const side = round(size * 1.06); // a hair of breathing room
    return `  ${JSON.stringify(name)}: "${round(cx - side / 2)} ${round(cy - side / 2)} ${side} ${side}",`;
  })
  .join("\n");

writeFileSync(
  new URL("../src/game/tree/icons.generated.ts", import.meta.url),
  `// Generated by scripts/extract-tree-icons.mjs — do not edit.
// Icons by Lorc, Delapouite & contributors — https://game-icons.net — CC BY 3.0.
/** Path data for each icon (drawn on a 512 × 512 canvas). */
export const TREE_ICONS: Record<string, string[]> = {
${entries}
};

/** Square viewBox per icon, fitted to its drawing so it renders centred and at a consistent size. */
export const ICON_VIEWBOX: Record<string, string> = {
${viewBoxes}
};

export const iconViewBox = (name: string) => ICON_VIEWBOX[name] ?? "0 0 512 512";
`,
);
console.log(`Wrote ${names.length} icons.`);
